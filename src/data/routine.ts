export function mapMuscleToGroups(muscleStr: string): string[] {
  const m = muscleStr.toLowerCase();
  const groups: string[] = [];
  if (m.includes('chest')) groups.push('Chest');
  if (m.includes('lat') || m.includes('mid back') || m.includes('back')) {
    if (!m.includes('lower back')) groups.push('Back / Lats');
  }
  if (m.includes('quad')) groups.push('Quads');
  if (m.includes('hamstring')) groups.push('Hamstrings');
  if (m.includes('side delt') || m.includes('shoulders')) groups.push('Side & Front Delts');
  if (m.includes('rear delt')) groups.push('Rear Delts');
  if (m.includes('bicep')) groups.push('Biceps');
  if (m.includes('tricep')) groups.push('Triceps');
  if (m.includes('glute')) groups.push('Glutes');
  if (m.includes('calv') || m.includes('soleus')) groups.push('Calves');
  if (m.includes('core') || m.includes('abs') || m.includes('oblique')) groups.push('Abs / Core');
  if (m.includes('trap')) groups.push('Traps');
  if (m.includes('neck')) groups.push('Neck');
  if (groups.length === 0) groups.push('Other');
  return groups;
}
