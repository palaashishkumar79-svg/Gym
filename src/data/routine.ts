export const WEEKDAY_ORDER: DayKey[] = ['MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT', 'SUN'];

export function getDayKeyFromDate(date: Date = new Date()): DayKey {
  const jsDay = date.getDay(); // 0=Sun, 1=Mon...
  const map: Record<number, DayKey> = {
    0: 'SUN',
    1: 'MON',
    2: 'TUE',
    3: 'WED',
    4: 'THU',
    5: 'FRI',
    6: 'SAT',
  };
  return map[jsDay];
}

